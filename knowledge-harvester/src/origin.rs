fn vendor_set() -> &'static RegexSet {
    static SET: OnceLock<RegexSet> = OnceLock::new();
    SET.get_or_init(|| RegexSet::new(VENDOR_PATTERNS).expect("valid vendor patterns"))
}

fn generated_set() -> &'static RegexSet {
    static SET: OnceLock<RegexSet> = OnceLock::new();
    SET.get_or_init(|| RegexSet::new(GENERATED_PATTERNS).expect("valid generated patterns"))
}

fn test_set() -> &'static RegexSet {
    static SET: OnceLock<RegexSet> = OnceLock::new();
    SET.get_or_init(|| RegexSet::new(TEST_PATTERNS).expect("valid test patterns"))
}

fn sync_subject() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        Regex::new(
            r"(?i)\b(vendor(ed|ing)?|update[sd]?|bump(ed|s)?|sync(ed|s)?|upgrade[sd]?|fetch(ed)?|import(ed)?|pull(ed)?|refresh(ed)?|regenerate[sd]?)\b.*\b(lib|libs|librar(y|ies)|dependenc(y|ies)|deps|vendor(ed)?|third[- ]?party|upstream|submodules?)\b",
        )
        .expect("valid sync subject pattern")
    })
}

pub fn is_sync_subject(subject: &str) -> bool {
    sync_subject().is_match(subject)
}

pub fn is_test_path(path: &str) -> bool {
    test_set().is_match(path)
}

pub fn is_vendored_path(path: &str) -> bool {
    vendor_set().is_match(path)
}

pub fn is_generated_path(path: &str) -> bool {
    generated_set().is_match(path)
}

const REPEATED_MARKERS: &[&str] = &[
    "auto generated",
    "auto-generated",
    "autogenerated",
    "automatically generated",
    "code generator",
    "do not edit",
];
const MIN_REPEATED_MARKERS: usize = 3;
const HEADER_LINES: usize = 40;

pub fn looks_generated(source: &str) -> bool {
    let head: String = source
        .lines()
        .take(HEADER_LINES)
        .collect::<Vec<_>>()
        .join("\n")
        .to_ascii_lowercase();
    if GENERATED_MARKERS.iter().any(|m| head.contains(m)) {
        return true;
    }
    let lower = source.to_ascii_lowercase();
    let repeated: usize = REPEATED_MARKERS
        .iter()
        .map(|m| lower.matches(m).count())
        .sum();
    if repeated >= MIN_REPEATED_MARKERS {
        return true;
    }
    let lines = source.lines().count().max(1);
    source.len() > 2_000 && source.len() / lines > 400
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Attribute {
    Vendored,
    Generated,
    Documentation,
}

struct Rule {
    matcher: Gitignore,
    attribute: Attribute,
    set: bool,
}

#[derive(Debug, Default, Clone, PartialEq)]
pub struct FileHistory {
    pub commits: u32,
    pub sync_commits: u32,
}

#[derive(Default)]
pub struct Classifier {
    root: PathBuf,
    rules: Vec<Rule>,
    history_vendored: HashSet<String>,
}

const MIN_HISTORY_COMMITS: usize = 30;

impl Classifier {
    pub fn load(
        root: &Path,
        attribute_files: &[PathBuf],
        history: &HashMap<String, FileHistory>,
        total_commits: usize,
    ) -> Self {
        let mut rules = Vec::new();
        let mut files: Vec<&PathBuf> = attribute_files.iter().collect();
        files.sort_by_key(|p| p.components().count());
        for file in files {
            let Ok(text) = std::fs::read_to_string(file) else {
                continue;
            };
            let dir = file.parent().unwrap_or(root);
            rules.extend(parse_attributes(dir, &text));
        }
        let history_vendored = if total_commits >= MIN_HISTORY_COMMITS {
            history
                .iter()
                .filter(|(_, h)| h.commits > 0 && h.sync_commits == h.commits)
                .map(|(path, _)| path.clone())
                .collect()
        } else {
            HashSet::new()
        };
        Self {
            root: root.to_path_buf(),
            rules,
            history_vendored,
        }
    }

    fn attribute(&self, path: &str, attribute: Attribute) -> Option<bool> {
        let absolute = self.root.join(path);
        self.rules
            .iter()
            .rev()
            .filter(|r| r.attribute == attribute)
            .find(|r| {
                absolute.starts_with(r.matcher.path())
                    && r.matcher
                        .matched_path_or_any_parents(&absolute, false)
                        .is_ignore()
            })
            .map(|r| r.set)
    }

    pub fn classify(&self, path: &str, source: &str) -> Origin {
        let generated = self.attribute(path, Attribute::Generated);
        let vendored = self.attribute(path, Attribute::Vendored);
        if generated == Some(true) {
            return Origin::Generated;
        }
        if vendored == Some(true) {
            return Origin::Vendored;
        }
        if generated.is_none() && (is_generated_path(path) || looks_generated(source)) {
            return Origin::Generated;
        }
        if vendored.is_none() && (is_vendored_path(path) || self.history_vendored.contains(path)) {
            return Origin::Vendored;
        }
        if self.attribute(path, Attribute::Documentation) == Some(true) {
            return Origin::Source;
        }
        if is_test_path(path) {
            return Origin::Test;
        }
        Origin::Source
    }
}

fn parse_attributes(dir: &Path, text: &str) -> Vec<Rule> {
    let mut rules = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut parts = line.split_whitespace();
        let Some(pattern) = parts.next() else {
            continue;
        };
        for attr in parts {
            let (name, set) = match attr.strip_prefix('-') {
                Some(name) => (name, false),
                None => match attr.split_once('=') {
                    Some((name, value)) => (name, !matches!(value, "false" | "0" | "no")),
                    None => (attr.trim_start_matches('!'), !attr.starts_with('!')),
                },
            };
            let attribute = match name {
                "linguist-vendored" => Attribute::Vendored,
                "linguist-generated" | "generated" => Attribute::Generated,
                "linguist-documentation" => Attribute::Documentation,
                _ => continue,
            };
            let mut builder = GitignoreBuilder::new(dir);
            if builder.add_line(None, pattern).is_err() {
                continue;
            }
            if let Ok(matcher) = builder.build() {
                rules.push(Rule {
                    matcher,
                    attribute,
                    set,
                });
            }
        }
    }
    rules
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn paths_are_classified_by_convention() {
        let c = Classifier::default();
        assert_eq!(c.classify("src/app/volume.py", "x = 1\n"), Origin::Source);
        assert_eq!(c.classify("tests/test_volume.py", ""), Origin::Test);
        assert_eq!(c.classify("pkg/volume_test.go", ""), Origin::Test);
        assert_eq!(
            c.classify("src/test/java/a/StoreTest.java", ""),
            Origin::Test
        );
        assert_eq!(c.classify("spec/models/user_spec.rb", ""), Origin::Test);
        assert_eq!(c.classify("vendor/github.com/x/y.go", ""), Origin::Vendored);
        assert_eq!(
            c.classify("web/node_modules/react/index.js", ""),
            Origin::Vendored
        );
        assert_eq!(
            c.classify("third_party/zlib/inflate.c", ""),
            Origin::Vendored
        );
        assert_eq!(c.classify("api/v1/service.pb.go", ""), Origin::Generated);
        assert_eq!(c.classify("app/bundle.min.js", ""), Origin::Generated);
        let codegen = format!(
            "# Copyright 2022 Example\n{}class A:\n    \"\"\"NOTE: This class is auto generated by the swagger code generator program.\"\"\"\nclass B:\n    \"\"\"NOTE: This class is auto generated by the swagger code generator program.\"\"\"\n",
            "#\n".repeat(60)
        );
        assert_eq!(
            c.classify("drivers/acme/api_client.py", &codegen),
            Origin::Generated
        );
        assert_eq!(
            c.classify(
                "drivers/acme/driver.py",
                "# Content-Type which generated by urllib3\nclass Driver:\n    pass\n"
            ),
            Origin::Source
        );
        assert_eq!(
            c.classify(
                "src/schema.rs",
                "// Code generated by sqlc. DO NOT EDIT.\nfn a() {}\n"
            ),
            Origin::Generated
        );
    }

    #[test]
    fn gitattributes_override_conventions() {
        let dir = tempfile::tempdir().unwrap();
        let attributes = dir.path().join(".gitattributes");
        std::fs::write(
            &attributes,
            "lib/charms/** linguist-vendored\nvendor/ours/** -linguist-vendored\nsrc/gen.rs linguist-generated=true\n",
        )
        .unwrap();
        let c = Classifier::load(dir.path(), &[attributes], &HashMap::new(), 0);
        assert_eq!(
            c.classify("lib/charms/grafana/v0/agent.py", ""),
            Origin::Vendored
        );
        assert_eq!(c.classify("vendor/ours/code.go", ""), Origin::Source);
        assert_eq!(c.classify("src/gen.rs", ""), Origin::Generated);
    }

    #[test]
    fn files_only_touched_by_dependency_syncs_are_vendored() {
        let mut history = HashMap::new();
        history.insert(
            "lib/charms/data/v0/interfaces.py".to_string(),
            FileHistory {
                commits: 3,
                sync_commits: 3,
            },
        );
        history.insert(
            "src/charm.py".to_string(),
            FileHistory {
                commits: 40,
                sync_commits: 2,
            },
        );
        let c = Classifier::load(Path::new("/r"), &[], &history, 200);
        assert_eq!(
            c.classify("lib/charms/data/v0/interfaces.py", ""),
            Origin::Vendored
        );
        assert_eq!(c.classify("src/charm.py", ""), Origin::Source);
        let young = Classifier::load(Path::new("/r"), &[], &history, 5);
        assert_eq!(
            young.classify("lib/charms/data/v0/interfaces.py", ""),
            Origin::Source
        );
        assert!(is_sync_subject("chore: update charm libraries"));
        assert!(is_sync_subject("Bump dependencies"));
        assert!(!is_sync_subject("Fix volume attach race"));
    }
}
