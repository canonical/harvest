#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Origin {
    #[default]
    Source,
    Test,
    Vendored,
    Generated,
}

impl Origin {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Source => "source",
            Self::Test => "test",
            Self::Vendored => "vendored",
            Self::Generated => "generated",
        }
    }
}

